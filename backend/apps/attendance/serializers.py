class RecordEventSerializer(serializers.Serializer):
    """The guard logs what they decided (Modules 7.2, 7.5, 7.6).

    ``id`` is generated by the *device*, not the server. That is what makes a
    retried submission idempotent, so it is required rather than optional — a
    server-generated id would defeat the entire offline design.
    """

    id = serializers.UUIDField(default=uuid.uuid4)
    worker = serializers.IntegerField()
    direction = serializers.ChoiceField(choices=Direction.choices, default=Direction.ENTRY)
    method = serializers.ChoiceField(
        choices=VerificationMethod.choices, default=VerificationMethod.QR
    )
    decision = serializers.ChoiceField(choices=Decision.choices, default=Decision.ALLOWED)
    decision_reason = serializers.CharField(
        required=False, allow_blank=True, default="", max_length=200
    )
    occurred_at = serializers.DateTimeField()
    gate = serializers.IntegerField(required=False, allow_null=True)
    device_id = serializers.CharField(
        required=False, allow_blank=True, default="", max_length=64
    )
    was_offline = serializers.BooleanField(default=False)

    def validate_decision_reason(self, value):
        return value.strip()

    def validate(self, attrs):
        if attrs["decision"] == Decision.DENIED and not attrs.get("decision_reason"):
            # A denial without a reason is unauditable, and the person turned
            # away deserves to know why.
            raise serializers.ValidationError(
                {"decision_reason": "Say why entry was refused."}
            )
        return attrs


class SelfCheckInSerializer(serializers.Serializer):
    """Module 13.3 tier 2 — a worker recording their own arrival.

    ``id`` is device-generated for the same reason it is on
    :class:`RecordEventSerializer`: this is a queueable event, and a worker who
    taps "I have arrived" with no signal must be able to retry without creating
    a second record.

    Position is optional. A phone with location switched off still produces a
    usable record — it just goes to an administrator rather than standing on its
    own. Refusing the check-in outright would leave a worker who did the job
    with no evidence of it, which is the failure this tier exists to prevent.
    """

    id = serializers.UUIDField(default=uuid.uuid4)
    direction = serializers.ChoiceField(
        choices=Direction.choices, default=Direction.ENTRY
    )
    occurred_at = serializers.DateTimeField()

    latitude = serializers.FloatField(required=False, allow_null=True)
    longitude = serializers.FloatField(required=False, allow_null=True)

    #: What the device says its own fix is worth, in metres. Honoured rather
    #: than ignored — a phone admitting to a 180 m fix is being truthful, and
    #: holding that against the person carrying it punishes them for standing
    #: next to a tall building.
    accuracy_metres = serializers.FloatField(required=False, allow_null=True)

    device_id = serializers.CharField(
        required=False, allow_blank=True, default="", max_length=64
    )
    was_offline = serializers.BooleanField(default=False)

    def validate(self, attrs):
        has_latitude = attrs.get("latitude") is not None
        has_longitude = attrs.get("longitude") is not None
        if has_latitude != has_longitude:
            raise serializers.ValidationError(
                {"latitude": "Send both latitude and longitude, or neither."}
            )
        return attrs


