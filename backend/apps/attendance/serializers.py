class OverrideSerializer(serializers.Serializer):
    """A guard resolves a below-threshold face match (Module 7.3).

    A reason is always required, in both directions. Overriding a biometric
    check — to let someone in or to keep them out — is exactly the decision that
    has to be answerable for later.
    """

    allow = serializers.BooleanField()
    reason = serializers.CharField(max_length=200)

    def validate_reason(self, value):
        if not value.strip():
            raise serializers.ValidationError("Say why you are overriding the check.")
        return value.strip()


