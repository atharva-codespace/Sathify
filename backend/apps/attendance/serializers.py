class SyncRequestSerializer(serializers.Serializer):
    """Module 7.4 — a guard device replaying its offline queue."""

    events = RecordEventSerializer(many=True)

    def validate_events(self, value):
        if not value:
            raise serializers.ValidationError("Send at least one event.")
        if len(value) > 500:
            # Bounded so one device cannot exhaust a free-tier instance's
            # memory with a runaway queue.
            raise serializers.ValidationError(
                "Sync at most 500 events at a time."
            )
        return value


